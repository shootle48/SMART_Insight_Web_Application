// ทำความสะอาด value_text ดิบจากโมเดลบางตัวก่อนเก็บลง DB
//
// เจอจริงจากโมเดล 7-segment: ส่งมาเป็น "['3dot145']" — ทั้ง Python list-repr หลุดมาทั้งดุ้น
// (เข้าใจว่าลืม .join()/["0"] ก่อน publish) และใช้คำว่า "dot" แทน "." ตรง ๆ
// (คาดว่ากันสับสนกับจุดทศนิยมตอน OCR อ่าน — ยังไม่ได้ถามทีม AI ตรง ๆ ว่าทำไม)
//
// ทำที่ ingest จุดเดียว ไม่ใช่ตอนแสดงผล เพราะ:
//   1. DB ควรเก็บค่าที่ใช้งานได้จริง ไม่ใช่ของดิบเพี้ยน ๆ — เว็บ/export/debug ในอนาคต
//      จะได้ไม่ต้องมาแกะซ้ำที่ปลายทางทุกจุด
//   2. throttle.ts เทียบ value_text ตัดสินว่า "ค่าเปลี่ยนไหม" — ต้องเทียบค่าที่ format
//      นิ่งแล้วเท่านั้น ไม่งั้น format ดิบที่ไม่สม่ำเสมอจะทำให้เทียบผิดพลาด

/**
 * แกะ value_text ดิบให้เป็นข้อความอ่านง่าย
 *
 * ตั้งใจ "พยายามทำให้ดีที่สุด" ไม่ throw ถ้ารูปแบบไม่ตรงเป๊ะ — คืนค่าดิบกลับไปเฉย ๆ
 * ดีกว่าทิ้งทั้งเฟรมเพราะ format แปลกไปนิดเดียว (กติกาเดียวกับทั้งไฟล์ ingest:
 * ข้อความเดียวพัง ห้ามทำให้ระบบหยุดรับข้อมูล)
 *
 * ถ้าเจอหลายค่าในสตริงเดียว (เช่น "['1234', '6789']") คั่นด้วย " / " ไว้ก่อน
 * ไม่ทิ้งข้อมูล — แต่ควรถามทีม AI ว่าตั้งใจส่งคู่กันจริงหรือเป็นความผิดพลาดของโมเดล
 */
export function cleanRawText(raw: string): string {
  const items = raw
    .trim()
    .replace(/^\[|\]$/g, "") // ตัดวงเล็บเหลี่ยมหัวท้ายถ้ามี (Python list-repr)
    .split(",")
    .map((s) => s.trim().replace(/^['"]|['"]$/g, "").trim()) // ตัด quote หัวท้ายแต่ละตัว
    .filter((s) => s.length > 0)
    .map((s) => s.replace(/dot/gi, ".")); // "3dot145" -> "3.145"

  if (items.length === 0) return raw; // แกะไม่ได้เลย เก็บของเดิมไว้ดีกว่าเก็บสตริงว่าง
  return items.join(" / ");
}

/**
 * ถ้าข้อความที่ทำความสะอาดแล้ว "เป็นตัวเลขล้วน" คืนเป็น number ไม่งั้นคืน null
 *
 * ทำไมต้องมี (T-023): SEVEN_SEGMENT กับ WATER_METER ของทีม AI ส่ง**เลขนับมาในช่อง
 * `value_text`** (ดู D-016) ทำให้ `value_num` เป็น null ทุกแถว ผลคือ
 *   - กราฟย้อนหลังวาดไม่ได้เลย (avg/min/max อ่านแต่ `value_num`)
 *   - **deadband ของ throttle ไม่ทำงาน** เพราะมันเทียบด้วยตัวเลข → เก็บทุกเฟรมเท่าที่
 *     เพดานอัตราอนุญาต ทั้งที่ค่าไม่ได้ขยับ
 * ต้นตออยู่ที่ edge ส่งผิดช่อง แต่ edge อยู่นอกขอบเขตเรา (D-020) จึงเติมให้ฝั่งเรา
 * โดย**ไม่ทิ้ง `value_text` เดิม** — ของที่ edge ส่งมายังอยู่ครบ แค่เพิ่มค่าที่ใช้งานได้ข้าง ๆ
 *
 * ⚠️ เงื่อนไขต้องตรงกับ regex ใน `api/points.ts` (history) เป๊ะ ไม่งั้นข้อมูลเก่ากับใหม่
 * จะถูกนับคนละแบบ แล้วกราฟจะมีรอยต่อแปลก ๆ ตรงวันที่ deploy
 */
export function numericFromText(text: string): number | null {
  const t = text.trim();
  if (!/^-?[0-9]+([.][0-9]+)?$/.test(t)) return null;
  const n = Number(t);
  return Number.isFinite(n) ? n : null;
}
